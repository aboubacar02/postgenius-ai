export const translations = { fr, en, es, pt }

const I18nContext = createContext(null)

function resolve(key, lang) {
  const dict = translations[lang] || fr
  if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key]
  if (Object.prototype.hasOwnProperty.call(fr, key)) return fr[key]
  return key
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('pg-lang')
      return LANGUAGES.some((l) => l.id === saved) ? saved : 'fr'
    } catch {
      return 'fr'
    }
  })

  useEffect(() => {
    const meta = LANGUAGES.find((l) => l.id === lang) || LANGUAGES[0]
    document.documentElement.lang = lang
    document.documentElement.dir = meta.dir
    try {
      localStorage.setItem('pg-lang', lang)
    } catch {
      /* stockage indisponible */
    }
  }, [lang])

  const value = useMemo(
    () => ({
      lang,
      setLang: setLangState,
      t: (key, vars = {}) => {
        const template = resolve(key, lang)
        if (typeof template !== 'string') return template
        return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`))
      }
    }),
    [lang]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n doit être utilisé dans un I18nProvider')
  return ctx
}
